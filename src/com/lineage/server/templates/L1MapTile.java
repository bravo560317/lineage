package com.lineage.server.templates;

public final class L1MapTile
{
    private int mapid;
    private int x;
    private int y;
    private int tile;
    
    public int getMapid() {
        return this.mapid;
    }
    
    public void setMapid(int mapid) {
        this.mapid = mapid;
    }
    
    public int getX() {
        return this.x;
    }
    
    public void setX(int x) {
        this.x = x;
    }
    
    public int getY() {
        return this.y;
    }
    
    public void setY(int y) {
        this.y = y;
    }
    
    public int getTile() {
        return this.tile;
    }
    
    public void setTile(int tile) {
        this.tile = tile;
    }
}
